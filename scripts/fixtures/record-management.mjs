import assert from 'node:assert/strict';

export async function testRecordManagement(db, f) {
  const one = async (sql, args=[]) => (await db.query(sql,args)).rows[0];
  const asUser = async id => {
    await db.exec('RESET ROLE');
    await db.query(`SELECT set_config('request.jwt.claim.sub',$1,false)`,[id]);
    await db.exec('SET ROLE authenticated');
  };
  const preview = async (table,id) => (await one('SELECT preview_record_deletion($1,$2) AS result',[table,id])).result;
  const remove = (table,id,title) => db.query('SELECT delete_staff_record($1,$2,$3)',[table,id,title]);
  await db.exec('RESET ROLE');
  await db.query(`SELECT set_config('request.jwt.claim.sub',$1,false)`,[f.admin]);
  const teacher = '00000000-0000-4000-8000-000000000095';
  await db.query(`INSERT INTO auth.users(id,email) VALUES($1,'deletion-teacher@example.invalid')`,[teacher]);
  await db.query(`INSERT INTO user_roles(user_id,role_id) SELECT $1,id FROM roles WHERE name='instructor'`,[teacher]);
  await db.query(`INSERT INTO cohort_instructors(cohort_id,instructor_id) VALUES($1,$2)`,[f.cohort,teacher]);
  await asUser(f.admin);
  const session = await one(`INSERT INTO live_sessions(cohort_id,title,scheduled_start,scheduled_end) VALUES($1,'Accidental session',now(),now()+interval '1 hour') RETURNING id`,[f.cohort]);
  await asUser(f.student);
  await assert.rejects(()=>preview('live_sessions',session.id),/administrator or assigned instructor/);
  await assert.rejects(()=>remove('live_sessions',session.id,'Accidental session'),/administrator or assigned instructor/);
  await asUser(teacher);
  assert.equal((await preview('live_sessions',session.id)).allowed,true);
  await assert.rejects(()=>remove('live_sessions',session.id,'Stale title'),/record changed/);
  await remove('live_sessions',session.id,'Accidental session');
  await assert.rejects(()=>preview('live_sessions',session.id),/no longer exists/);
  await asUser(f.admin);
  const attended = await one(`INSERT INTO live_sessions(cohort_id,title,scheduled_start,scheduled_end) VALUES($1,'Attended session',now(),now()+interval '1 hour') RETURNING id`,[f.cohort]);
  await db.query(`INSERT INTO attendance_records(live_session_id,student_id,enrolment_id) VALUES($1,$2,$3)`,[attended.id,f.student,f.enrol]);
  assert.equal((await preview('live_sessions',attended.id)).allowed,false);
  await assert.rejects(()=>remove('live_sessions',attended.id,'Attended session'),/linked records/);
  await assert.rejects(()=>db.query('DELETE FROM live_sessions WHERE id=$1',[attended.id]),/linked records/);
  assert.equal((await one('SELECT count(*)::int AS n FROM attendance_records WHERE live_session_id=$1',[attended.id])).n,1);
  const quiz = await one(`INSERT INTO assessments(cohort_id,title,assessment_type) VALUES($1,'Accidental quiz','quiz') RETURNING id`,[f.cohort]);
  await db.query(`INSERT INTO assessment_questions(assessment_id,question_text) VALUES($1,'Question')`,[quiz.id]);
  assert.equal((await preview('assessments',quiz.id)).allowed,true);
  await remove('assessments',quiz.id,'Accidental quiz');
  assert.equal((await one('SELECT count(*)::int AS n FROM assessment_questions WHERE assessment_id=$1',[quiz.id])).n,0);
  assert.equal((await preview('assessments',f.checks['graded-quiz-1'])).allowed,false);
  const usedAssignment=await one('SELECT assignment_id AS id FROM submissions LIMIT 1');
  assert.equal((await preview('assignments',usedAssignment.id)).allowed,false);
  const assignment=await one(`INSERT INTO assignments(cohort_id,title) VALUES($1,'Accidental assignment') RETURNING id`,[f.cohort]);
  await remove('assignments',assignment.id,'Accidental assignment');
  const checkpoint=await one(`INSERT INTO assignments(cohort_id,title,assignment_type) VALUES($1,'Resource checkpoint','activity') RETURNING id`,[f.cohort]);
  await db.query(`INSERT INTO resources(course_id,cohort_id,title,release_mode,release_checkpoint_type,release_checkpoint_id) VALUES($1,$2,'Gated resource','checkpoint','activity',$3)`,[f.course,f.cohort,checkpoint.id]);
  const checkpointReview=await preview('assignments',checkpoint.id);
  assert.equal(checkpointReview.allowed,false);
  assert.ok(checkpointReview.dependencies.some(row=>row.source==='resource release checkpoints'));
  await assert.rejects(()=>remove('assignments',checkpoint.id,'Resource checkpoint'),/linked records/);
  assert.equal((await preview('cohorts',f.cohort)).allowed,false);
  const emptyCohort=await one(`INSERT INTO cohorts(course_id,name,slug) VALUES($1,'Empty QA cohort','deletion-empty') RETURNING id`,[f.course]);
  const otherSession=await one(`INSERT INTO live_sessions(cohort_id,title,scheduled_start,scheduled_end) VALUES($1,'Other cohort session',now(),now()+interval '1 hour') RETURNING id`,[emptyCohort.id]);
  await asUser(teacher);
  await assert.rejects(()=>preview('cohorts',emptyCohort.id),/administrator or assigned instructor/);
  await assert.rejects(()=>remove('live_sessions',otherSession.id,'Other cohort session'),/administrator or assigned instructor/);
  await asUser(f.admin);
  await remove('live_sessions',otherSession.id,'Other cohort session');
  await remove('cohorts',emptyCohort.id,'Empty QA cohort');
  const category=await one(`INSERT INTO course_categories(name,slug) VALUES('Accidental category','deletion-category') RETURNING id`);
  await db.query('INSERT INTO course_categories_join(course_id,category_id) VALUES($1,$2)',[f.course,category.id]);
  assert.equal((await preview('course_categories',category.id)).allowed,false);
  const emptyCategory=await one(`INSERT INTO course_categories(name,slug) VALUES('Empty category','deletion-empty-category') RETURNING id`);
  await remove('course_categories',emptyCategory.id,'Empty category');
  const announcement=await one(`INSERT INTO announcements(cohort_id,title,body) VALUES($1,'Accidental announcement','QA') RETURNING id`,[f.cohort]);
  await remove('announcements',announcement.id,'Accidental announcement');
  assert.equal((await one(`SELECT count(*)::int AS n FROM audit_log WHERE entity_id=$1 AND action='delete'`,[announcement.id])).n,1);
  await assert.rejects(()=>preview('profiles',f.student),/does not support/);
  await assert.rejects(()=>db.query('UPDATE profiles SET is_active=false WHERE id=$1',[f.admin]),/own administrator|own account/);
  await db.query('UPDATE profiles SET is_active=false WHERE id=$1',[f.student]);
  await asUser(f.student);
  assert.equal((await one('SELECT is_enrolled($1) AS enrolled',[f.cohort])).enrolled,false);
  assert.deepEqual((await one('SELECT get_user_roles() AS roles')).roles,[]);
  await assert.rejects(()=>db.query('UPDATE profiles SET is_active=true WHERE id=$1',[f.student]),/Only an active administrator/);
  await assert.rejects(()=>preview('live_sessions',attended.id),/active staff account/);
  await asUser(f.admin);
  await db.query('UPDATE profiles SET is_active=true WHERE id=$1',[f.student]);
  await asUser(f.student);
  assert.equal((await one('SELECT is_enrolled($1) AS enrolled',[f.cohort])).enrolled,true);
  await db.exec('RESET ROLE; SET ROLE anon');
  await assert.rejects(()=>preview('cohorts',f.cohort),/permission denied/);
  await db.exec('RESET ROLE');
  console.log('PASS safe record deletion, linked-history protection, direct-delete guard, instructor scope, stale title, audit path, account disable/enable, self-reactivation denial and anonymous denial.');
}
